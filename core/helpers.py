from __future__ import annotations

from datetime import datetime

import pandas as pd


# -------------------------------------------------------------------------
# Safe Float
# -------------------------------------------------------------------------

def safe_float(value):

    try:

        return float(value)

    except Exception:

        return 0.0


# -------------------------------------------------------------------------
# Safe Int
# -------------------------------------------------------------------------

def safe_int(value):

    try:

        return int(value)

    except Exception:

        return 0


# -------------------------------------------------------------------------
# Safe String
# -------------------------------------------------------------------------

def safe_string(value):

    if value is None:

        return ""

    return str(value).strip()


# -------------------------------------------------------------------------
# Parse Date
# -------------------------------------------------------------------------

def parse_date(value):

    if value is None:

        return None

    formats = [

        "%d/%m/%Y",

        "%d-%m-%Y",

        "%d/%b/%Y",

        "%d-%b-%Y",

        "%d/%B/%Y"

    ]

    value = str(value).strip()

    for fmt in formats:

        try:

            return datetime.strptime(

                value,

                fmt

            )

        except Exception:

            pass

    return None


# -------------------------------------------------------------------------
# Currency
# -------------------------------------------------------------------------

def currency(value):

    return f"₹{value:,.2f}"


# -------------------------------------------------------------------------
# Percentage
# -------------------------------------------------------------------------

def percentage(value):

    return f"{value:.2f} %"


# -------------------------------------------------------------------------
# DataFrame Empty
# -------------------------------------------------------------------------

def dataframe_empty(df: pd.DataFrame):

    return (

        df is None

        or

        df.empty

    )


# -------------------------------------------------------------------------
# Today
# -------------------------------------------------------------------------

def today():

    return datetime.today()


# -------------------------------------------------------------------------
# Days Difference
# -------------------------------------------------------------------------

def days_between(

    start,

    end

):

    start = parse_date(start)

    end = parse_date(end)

    if start is None or end is None:

        return 0

    return (

        end

        - start

    ).days


# -------------------------------------------------------------------------
# Years Difference
# -------------------------------------------------------------------------

def years_between(

    start,

    end

):

    return round(

        days_between(

            start,

            end

        ) / 365.25,

        2

    )


# -------------------------------------------------------------------------
# Round Value
# -------------------------------------------------------------------------

def round2(value):

    return round(

        safe_float(value),

        2

    )


# -------------------------------------------------------------------------
# Round Units
# -------------------------------------------------------------------------

def round_units(value):

    return round(

        safe_float(value),

        6

    )


# -------------------------------------------------------------------------
# Timestamp
# -------------------------------------------------------------------------

def timestamp():

    return datetime.now()


# -------------------------------------------------------------------------
# Remove Duplicates
# -------------------------------------------------------------------------

def unique(items):

    return list(

        dict.fromkeys(items)

    )


# -------------------------------------------------------------------------
# Chunk List
# -------------------------------------------------------------------------

def chunk_list(

    values,

    size

):

    for i in range(

        0,

        len(values),

        size

    ):

        yield values[i:i + size]